import type { Region, RegionCode, RegionId, RegionSlug } from "@opika/domain";

/**
 * The 27 first-level units, the source of truth for `regions` (migration `0020` inserts the same
 * rows; `regions-data.test.ts` fails if they drift). Ids are `uuidV5(code)` in `uuid-v5.ts`,
 * written out here so a changed namespace cannot silently renumber them.
 *
 * `neighbours` is app data only (the empty state of a region suggests next-door regions); it is
 * hand-authored, symmetric by test, and never used in SQL.
 */
export type RegionRecord = Region & { readonly neighbours: readonly RegionSlug[] };

function region(
  code: string,
  id: string,
  slug: string,
  kind: Region["kind"],
  uk: string,
  ukShort: string,
  ukLabel: string,
  en: string,
  neighbours: readonly string[],
): RegionRecord {
  return {
    id: id as RegionId,
    code: code as RegionCode,
    kind,
    slug: slug as RegionSlug,
    name: { uk, ukShort, ukLabel, en },
    neighbours: neighbours as readonly RegionSlug[],
  };
}

