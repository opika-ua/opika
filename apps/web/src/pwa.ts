import { readFileSync } from "node:fs";
import { join } from "node:path";
import { SITE_TITLE, titled, WORDMARK } from "./brand";

/**
 * `--color-page` read from the stylesheet at build time, so the token stays the only place the
 * colour is written. Throws (failing the build) if the token goes missing.
 */
function readPageColor(): string {
  const css = readFileSync(join(process.cwd(), "src/app/globals.css"), "utf8");
  const match = /--color-page:\s*(#[0-9a-fA-F]{6})\s*;/.exec(css);
  if (!match?.[1]) throw new Error("--color-page not found in globals.css");
  return match[1];
}

export const PAGE_COLOR = readPageColor();

